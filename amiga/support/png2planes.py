#!/usr/bin/env python3
"""Turn an indexed PNG into Amiga bitplanes as C: palette and ByteRun1 data.

Rows are packed as in an ILBM BODY: each row, plane 0 first, every plane
row compressed on its own. Plain Python (zlib only), so builds need no
imaging library.

Usage: png2planes.py <in.png> <name> <out.c>
"""
import struct
import sys
import zlib


def read_png(path):
    data = open(path, "rb").read()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        sys.exit(f"{path}: not a PNG")
    pos, idat, palette = 8, b"", []
    while pos < len(data):
        length, kind = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + length]
        pos += 12 + length
        if kind == b"IHDR":
            width, height, depth, colour_type = struct.unpack(">IIBB", body[:10])
            if colour_type != 3:
                sys.exit(f"{path}: not an indexed PNG")
        elif kind == b"PLTE":
            palette = [tuple(body[i:i + 3]) for i in range(0, len(body), 3)]
        elif kind == b"IDAT":
            idat += body
    raw = zlib.decompress(idat)
    stride = (width * depth + 7) // 8
    rows, prev = [], bytearray(stride)
    for y in range(height):
        kind = raw[y * (stride + 1)]
        line = bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for i in range(stride):
            a = line[i - 1] if i else 0
            b, c = prev[i], prev[i - 1] if i else 0
            if kind == 1:
                line[i] = (line[i] + a) & 255
            elif kind == 2:
                line[i] = (line[i] + b) & 255
            elif kind == 3:
                line[i] = (line[i] + (a + b) // 2) & 255
            elif kind == 4:
                p = a + b - c
                pred = a if abs(p - a) <= abs(p - b) and abs(p - a) <= abs(p - c) else (
                    b if abs(p - b) <= abs(p - c) else c)
                line[i] = (line[i] + pred) & 255
        prev = line
        per_byte = 8 // depth
        rows.append([(line[x // per_byte] >> (8 - depth * (x % per_byte + 1))) & ((1 << depth) - 1)
                     for x in range(width)])
    return width, height, palette, rows


def byterun1(row):
    out, i = bytearray(), 0
    while i < len(row):
        run = 1
        while i + run < len(row) and row[i + run] == row[i] and run < 128:
            run += 1
        if run > 1:
            out += bytes([(257 - run) & 255, row[i]])
            i += run
            continue
        start = i
        while i < len(row) and i - start < 128 and not (i + 1 < len(row) and row[i + 1] == row[i]):
            i += 1
        if i == start:
            i += 1
        out += bytes([i - start - 1]) + bytes(row[start:i])
    return out


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    width, height, palette, rows = read_png(sys.argv[1])
    name = sys.argv[2]
    # Pillow writes a full palette; the pens in use set the depth
    depth = max(1, max(max(row) for row in rows).bit_length())
    palette = palette[:1 << depth]
    if width % 16:
        sys.exit("width must be a multiple of 16")
    body = bytearray()
    for row in rows:
        for plane in range(depth):
            bits = bytearray(width // 8)
            for x, pen in enumerate(row):
                if pen >> plane & 1:
                    bits[x // 8] |= 0x80 >> (x % 8)
            body += byterun1(bits)
    with open(sys.argv[3], "w") as f:
        f.write(f"/* Generated by amiga/support/png2planes.py from {sys.argv[1]}; do not edit. */\n\n")
        f.write(f"const unsigned short {name}_width = {width}, {name}_height = {height}, "
                f"{name}_depth = {depth};\n")
        f.write(f"const unsigned short {name}_palette[{1 << depth}] = {{\n  ")
        f.write(", ".join(f"0x{r >> 4:X}{g >> 4:X}{b >> 4:X}" for r, g, b in
                          palette + [(0, 0, 0)] * ((1 << depth) - len(palette))))
        f.write("\n};\n")
        f.write(f"const unsigned long {name}_size = {len(body)};\n")
        f.write(f"const unsigned char {name}_planes[{len(body)}] = {{\n")
        for i in range(0, len(body), 20):
            f.write("  " + ", ".join(str(v) for v in body[i:i + 20]) + ",\n")
        f.write("};\n")


if __name__ == "__main__":
    main()
